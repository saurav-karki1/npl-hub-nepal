/** Get all players */
export function getAllPlayers(): Player[] {
  return NPL_PLAYERS;
}

/** Lookup a single player by slug or ID */
export function getPlayerBySlug(slug: string): Player | undefined {
  const normalized = slug.trim().toLowerCase();
  return NPL_PLAYERS.find(
    (p) => p.slug.toLowerCase() === normalized || p.id.toLowerCase() === normalized
  );
}

/** Get all players for a specific team */
export function getPlayersByTeam(teamId: string): Player[] {
  return NPL_PLAYERS.filter((p) => p.teamId === teamId);
}

/** Get all players with a specific role */
export function getPlayersByRole(role: PlayerRole): Player[] {
  return NPL_PLAYERS.filter((p) => p.role === role);
}

/** Get all player slugs for SSG generateStaticParams */
export function getAllPlayerSlugs(): { slug: string }[] {
  return NPL_PLAYERS.map((p) => ({ slug: p.slug }));
}

/** Resolve team detail for a given player without duplicating data */
export function getPlayerTeam(player: Player): TeamDetail | undefined {
  return getTeamBySlug(player.teamId);
}
